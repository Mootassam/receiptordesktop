const dicts: Record<Lang, Dict> = { en, zh, ru, es };

/** Returns a translator `t(key)` for the given language, falling back to English then the key itself. */
export const makeT = (lang: Lang) => (key: string | undefined): string => {
  if (!key) return "";
  return dicts[lang]?.[key] ?? en[key] ?? key;
};
