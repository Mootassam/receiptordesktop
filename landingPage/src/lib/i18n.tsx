const dicts: Record<Lang, Dict> = { zh, en, ru, es };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: string) => string };
const I18nContext = React.createContext<Ctx | null>(null);

const STORAGE_KEY = "crp_lang";
const VALID_LANGS: Lang[] = ["zh", "en", "ru", "es"];

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = React.useState<Lang>("zh");

  React.useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (saved && VALID_LANGS.includes(saved)) setLangState(saved);
    } catch {}
  }, []);

  React.useEffect(() => {
    if (typeof document !== "undefined") {
      const htmlLang: Record<Lang, string> = { zh: "zh-CN", en: "en", ru: "ru", es: "es" };
      document.documentElement.lang = htmlLang[lang];
    }
  }, [lang]);

  const setLang = React.useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem(STORAGE_KEY, l); } catch {}
  }, []);

  const t = React.useCallback((k: string) => dicts[lang][k] ?? dicts.en[k] ?? k, [lang]);

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = React.useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

const LANG_OPTIONS: { code: Lang; label: string }[] = [
  { code: "zh", label: "中文" },
  { code: "en", label: "EN" },
  { code: "ru", label: "RU" },
  { code: "es", label: "ES" },
];

export function LanguageSwitcher({ className = "" }: { className?: string }) {
  const { lang, setLang } = useI18n();
  return (
    <div
      role="group"
      aria-label="Language"
      className={`inline-flex items-center rounded-full border border-border bg-card/70 backdrop-blur p-0.5 text-xs font-semibold ${className}`}
    >
      {LANG_OPTIONS.map((opt) => (
        <button
          key={opt.code}
          type="button"
          onClick={() => setLang(opt.code)}
          aria-pressed={lang === opt.code}
          className={`px-2.5 py-1 rounded-full transition ${lang === opt.code ? "bg-primary text-primary-foreground" : "text-muted-foreground hover:text-foreground"}`}
        >
          {opt.label}
        </button>
      ))}
    </div>
  );
}
